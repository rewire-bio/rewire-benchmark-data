"""Score how complete the knowledge base is, from the record store.

Usage: python3 scripts/enrich/scorecard.py [--write]

Prints the scorecard as Markdown. With --write it also writes docs/scorecard.md. Run it after any
batch that fills in records, so the change in completeness is visible in the pull request.
"""
import collections
import datetime
import glob
import json
import sys


def read(path):
    with open(path) as handle:
        return [json.loads(line) for line in handle if line.strip()]


def entity(kind):
    return read(f"data/entities/{kind}.jsonl")


def links(record, *relations):
    return [link["target_id"] for link in record.get("links") or [] if link["relation"] in relations]


def fact_ok(record, label):
    profile = record["attributes"].get("profile")
    if not isinstance(profile, dict):
        return False
    return any(f.get("label") == label and f.get("status", "source_checked") == "source_checked" for f in profile.get("facts", []))


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def main():
    models, methods, benchmarks = entity("models"), entity("methods"), entity("benchmarks")
    protocols, tasks, use_cases = entity("protocols"), entity("tasks"), entity("use-cases")
    configurations, sources = entity("configurations"), {s["id"]: s for s in entity("sources")}
    parent = {c["id"]: (links(c, "configuration_of", "variant_of", "family", "uses_model") or [None])[0] for c in configurations}
    evaluations = {}
    for path in glob.glob("data/evidence/evaluations/*.jsonl"):
        for e in read(path):
            evaluations[e["id"]] = e
    per_system, per_protocol, origins, statuses = collections.Counter(), collections.defaultdict(set), collections.Counter(), collections.Counter()
    cells = collections.defaultdict(set)
    total = 0
    for path in glob.glob("data/evidence/results/*.jsonl"):
        for r in read(path):
            total += 1
            statuses[r["status"]] += 1
            e = evaluations.get((links(r, "evaluation") or [None])[0])
            if not e:
                continue
            system = (links(e, "system") or [None])[0]
            assessment = (links(e, "assessment") or [None])[0]
            origins[e["attributes"].get("origin", "unreported")] += 1
            owner = system
            for _ in range(4):
                if parent.get(owner):
                    owner = parent[owner]
            per_system[owner] += 1
            study = tuple(sorted({(sources.get(s, {}).get("attributes", {}).get("doi") or s) for s in (r.get("source_ids") or e.get("source_ids") or [])}))
            per_protocol[assessment].add(study)
            cells[(owner, assessment, r["attributes"].get("metric"))].add(study)

    def by_tier(records, columns):
        rows = []
        for tier in (1, 2, 3, None):
            group = [r for r in records if r["attributes"].get("depth_tier") == tier]
            if group:
                rows.append([tier if tier else "none", len(group)] + [sum(bool(test(r)) for r in group) for _, test in columns])
        return table(["Tier", "Records"] + [name for name, _ in columns], rows)

    today = datetime.date.today().isoformat()
    with_results = [p for p in protocols if per_protocol.get(p["id"])]
    out = [
        "# Knowledge base scorecard",
        "",
        f"Generated by `scripts/enrich/scorecard.py` on {today} from the record store. Each number is a count of records.",
        "",
        "## Models",
        "",
        by_tier(models, [
            ("Profile", lambda r: isinstance(r["attributes"].get("profile"), dict)),
            ("Parameters stated", lambda r: fact_ok(r, "Parameters")),
            ("A licence stated", lambda r: r["attributes"].get("licence") or fact_ok(r, "Weights licence") or fact_ok(r, "Code licence")),
            ("Run guide", lambda r: r["attributes"].get("run_guide")),
            ("Has results", lambda r: per_system.get(r["id"])),
        ]),
        "",
        "## Benchmarks",
        "",
        by_tier(benchmarks, [
            ("Profile", lambda r: isinstance(r["attributes"].get("profile"), dict)),
            ("Run guide or recipe", lambda r: r["attributes"].get("run_guide") or r["attributes"].get("run_recipes")),
            ("Run documentation only", lambda r: r["attributes"].get("run_documentation") and not (r["attributes"].get("run_guide") or r["attributes"].get("run_recipes"))),
        ]),
        "",
        "## Methods",
        "",
        by_tier(methods, [
            ("Profile", lambda r: isinstance(r["attributes"].get("profile"), dict)),
            ("Has results", lambda r: per_system.get(r["id"])),
        ]),
        "",
        "## Protocols and comparability",
        "",
        table(["Measure", "Count"], [
            ["Protocols", len(protocols)],
            ["Protocols with results", len(with_results)],
            ["of those, linked to a task or benchmark", sum(bool(links(p, "evaluates_task", "part_of")) for p in with_results)],
            ["of those, with results from two or more studies", sum(len(per_protocol[p["id"]]) >= 2 for p in with_results)],
            ["Tasks", len(tasks)],
            ["Model, test and metric combinations", len(cells)],
            ["of those, measured by two or more studies", sum(len(v) >= 2 for v in cells.values())],
        ]),
        "",
        "## Results",
        "",
        table(["Measure", "Count"], [["Results", total]] + [[f"from evaluations with origin `{k}`", v] for k, v in origins.most_common()] + [[f"with status `{k}`", v] for k, v in statuses.most_common()]),
        "",
        "## Use cases",
        "",
        by_tier(use_cases, [("Linked to a protocol", lambda r: links(r, "assessed_by"))]),
        "",
    ]
    text = "\n".join(out)
    print(text)
    if "--write" in sys.argv:
        with open("docs/scorecard.md", "w") as handle:
            handle.write(text)


if __name__ == "__main__":
    main()
