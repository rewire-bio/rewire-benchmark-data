# Records


def find_record(record_id: str, entities: Path = ENTITIES) -> dict:
    for path in sorted(entities.glob("*.jsonl")):
        with path.open(encoding="utf-8") as handle:
            for line in handle:
                if record_id not in line:
                    continue
                record = json.loads(line)
                if record.get("id") == record_id:
                    if not (record.get("attributes") or {}).get("run_guide"):
                        raise SystemExit(f"{record_id} has no run guide")
                    return record
    raise SystemExit(f"No record {record_id} in {entities}")


def records_with_guides(entities: Path = ENTITIES):
    for path in sorted(entities.glob("*.jsonl")):
        with path.open(encoding="utf-8") as handle:
            for line in handle:
                if '"run_guide"' not in line:
                    continue
                record = json.loads(line)
                if (record.get("attributes") or {}).get("run_guide"):
                    yield record


def guide_hash(guide: dict) -> str:
    canonical = json.dumps(guide, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def guide_python(guide: dict) -> str:
    """The Python version the prerequisites name, only when they name exactly one."""
    found = set()
    for text in guide.get("prerequisites", []):
        found.update(re.findall(r"\bPython (3\.\d{1,2})\b", text))
    return found.pop() if len(found) == 1 else ""


# Script


def heredoc_delimiter(base: str, text: str) -> str:
    delimiter, n = base, 0
    while delimiter in text:
        n += 1
        delimiter = f"{base}_{n}"
    return delimiter


SCRIPT_HEAD = r"""#!/usr/bin/env bash
# Trial of the run guide of {record_id}
# Run guide sha256: {sha}
# Generated by scripts/runs/trial.py. Usage: bash <this file> <trial dir>
#
# Optional environment:
#   TRIAL_TIMEOUT_SECONDS  stop the whole session after this many seconds (needs GNU timeout)
#   TRIAL_VENV             a Python venv to activate before the first step
#   TRIAL_CONDA            a conda installation whose shell functions are loaded first
set -u
if [ $# -ne 1 ]; then echo "usage: $0 <trial dir>" >&2; exit 2; fi
mkdir -p "$1" || exit 2
TRIAL_DIR=$(cd "$1" && pwd) || exit 2
RECORD="$TRIAL_DIR/record"
if [ -e "$RECORD/status.tsv" ]; then echo "$RECORD already holds a run" >&2; exit 2; fi
mkdir -p "$TRIAL_DIR/work" "$TRIAL_DIR/full-logs" "$RECORD/steps" "$RECORD/logs" || exit 2
: > "$RECORD/status.tsv"
printf '%s\n' '{record_id}' > "$RECORD/record-id"
printf '%s\n' '{sha}' > "$RECORD/guide.sha256"
"""

SESSION_HEAD = r"""set -e
__rg_now() { if [ -n "${EPOCHREALTIME:-}" ]; then printf '%s' "$EPOCHREALTIME"; else date +%s; fi; }
__rg_step=0
__rg_on_exit() {
  __rg_code=$?
  if [ "$__rg_step" -ne 0 ]; then
    printf 'end\t%s\t%s\t%s\texit\n' "$__rg_step" "$(__rg_now)" "$__rg_code" >> "$__RG_RECORD/status.tsv"
  fi
  pwd > "$__RG_RECORD/final-cwd" 2>/dev/null || true
}
trap __rg_on_exit EXIT
cd "$__RG_WORK"
export CONDA_ALWAYS_YES=true PIP_NO_INPUT=1 DEBIAN_FRONTEND=noninteractive
if [ -n "${TRIAL_CONDA:-}" ] && [ -f "$TRIAL_CONDA/etc/profile.d/conda.sh" ]; then
  . "$TRIAL_CONDA/etc/profile.d/conda.sh"
  if [ -x "$TRIAL_CONDA/bin/mamba" ]; then
    export MAMBA_ROOT_PREFIX="$TRIAL_CONDA"
    eval "$("$TRIAL_CONDA/bin/mamba" shell hook --shell bash)" || true
  fi
fi
if [ -n "${TRIAL_VENV:-}" ]; then . "$TRIAL_VENV/bin/activate"; fi
{ command -v python3 && python3 --version; } > "$__RG_RECORD/session-python.txt" 2>&1 || true
{ conda --version && mamba --version | head -n 1; } > "$__RG_RECORD/session-conda.txt" 2>&1 || true
"""

SESSION_STEP = r"""
__rg_step={n}
printf 'begin\t{n}\t%s\n' "$(__rg_now)" >> "$__RG_RECORD/status.tsv"
. "$__RG_RECORD/steps/{n}.sh" > "$__RG_FULL/{n}.log" 2>&1 < /dev/null
printf 'end\t{n}\t%s\t0\tnormal\n' "$(__rg_now)" >> "$__RG_RECORD/status.tsv"
__rg_step=0
"""

SCRIPT_TAIL = r"""
export __RG_RECORD="$RECORD" __RG_WORK="$TRIAL_DIR/work" __RG_FULL="$TRIAL_DIR/full-logs"
printf 'started_at\t%s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" > "$RECORD/run.tsv"
printf 'timeout_seconds\t%s\n' "${TRIAL_TIMEOUT_SECONDS:-}" >> "$RECORD/run.tsv"
printf 'disk_free_kb_at_start\t%s\n' "$(df -Pk "$TRIAL_DIR" | awk 'NR == 2 { print $4 }')" >> "$RECORD/run.tsv"
cd "$TRIAL_DIR/work" || exit 2
start=$(date +%s)
if [ -n "${TRIAL_TIMEOUT_SECONDS:-}" ] && command -v timeout > /dev/null 2>&1; then
  timeout --signal=TERM --kill-after=30 "$TRIAL_TIMEOUT_SECONDS" bash --noprofile --norc "$RECORD/session.sh"
  code=$?
else
  bash --noprofile --norc "$RECORD/session.sh"
  code=$?
fi
elapsed=$(( $(date +%s) - start ))
timed_out=no
if [ -n "${TRIAL_TIMEOUT_SECONDS:-}" ] && [ "$elapsed" -ge "$TRIAL_TIMEOUT_SECONDS" ]; then timed_out=yes; fi
printf 'finished_at\t%s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" >> "$RECORD/run.tsv"
printf 'session_exit\t%s\n' "$code" >> "$RECORD/run.tsv"
printf 'timed_out\t%s\n' "$timed_out" >> "$RECORD/run.tsv"
for log in "$TRIAL_DIR/full-logs"/*.log; do
  [ -f "$log" ] || continue
  tail -n {tail} "$log" > "$RECORD/logs/$(basename "$log")"
done
exit 0
"""


def render_script(record: dict) -> str:
    guide = record["attributes"]["run_guide"]
    record_id = record["id"]
    if not ID_RE.match(record_id):
        raise SystemExit(f"Unexpected characters in record id {record_id!r}")
    sha = guide_hash(guide)
    parts = [SCRIPT_HEAD.format(record_id=record_id, sha=sha)]
    for n, step in enumerate(guide["steps"], start=1):
        shell = step["shell"].rstrip("\n")
        delimiter = heredoc_delimiter(f"RUN_GUIDE_STEP_{n}_END", shell)
        title = step["title"].replace("\n", " ")
        parts.append(
            f"\n# Step {n}: {title}\n"
            f"cat > \"$RECORD/steps/{n}.sh\" <<'{delimiter}'\n{shell}\n{delimiter}\n"
        )
    session = SESSION_HEAD + "".join(SESSION_STEP.format(n=n) for n in range(1, len(guide["steps"]) + 1))
    delimiter = heredoc_delimiter("RUN_GUIDE_SESSION_END", session)
    parts.append(f"\ncat > \"$RECORD/session.sh\" <<'{delimiter}'\n{session}{delimiter}\n")
    parts.append(SCRIPT_TAIL.replace("{tail}", str(LOG_TAIL_LINES)))
    return "".join(parts)


