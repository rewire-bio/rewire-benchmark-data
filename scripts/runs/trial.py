ERROR_LINE_RE = re.compile(r"error|exception|traceback|failed|not found|fatal|killed|denied", re.I)


def last_error_line(log_tail: str) -> str:
    """The last line that reads like an error, or the last line."""
    lines = [line.strip() for line in log_tail.splitlines() if line.strip()]
    for line in reversed(lines):
        if ERROR_LINE_RE.search(line):
            return line
    return lines[-1] if lines else ""


def is_manual(shell: str) -> bool:
    """A step whose shell holds only comments: something the reader does by hand."""
    return all(not line.strip() or line.lstrip().startswith("#") for line in shell.splitlines())


def likely_cause(log_tail: str, exit_code: int | None = None) -> str:
    """The first rule matching the last error line, else the first matching anywhere in the tail."""
    if exit_code == 127:
        return "tool_not_installed"
    for text in (last_error_line(log_tail), log_tail):
        for cause, pattern in CAUSE_RULES:
            if cause != "code_raised_error" and pattern.search(text):
                return cause
    if CAUSE_RULES[-1][1].search(log_tail):
        return "code_raised_error"
    if exit_code == 137:
        return "out_of_memory"
    return "other"


# Receipt


def read_tsv(path: Path) -> list[list[str]]:
    if not path.is_file():
        return []
    return [line.split("\t") for line in path.read_text(encoding="utf-8", errors="replace").splitlines() if line]


def to_seconds(value: str) -> float:
    return float(value.replace(",", "."))


def output_paths(outputs: list[str]) -> list[str]:
    """Path-like tokens in the guide's outputs, which are written as prose."""
    names: list[str] = []
    for text in outputs:
        for token in re.findall(r"[A-Za-z0-9_./*-]+", text):
            token = token.strip(".,;:")
            if not token or "*" in token or token.startswith(("http", "-", "/")) or ".." in token:
                continue
            if not re.search(r"[A-Za-z]", token):
                continue
            has_extension = re.search(r"[A-Za-z0-9_-]\.[A-Za-z][A-Za-z0-9]{0,5}$", token)
            if ("/" in token or has_extension) and token not in names:
                names.append(token)
    return names


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def inside(path: Path, root: Path) -> bool:
    try:
        path.resolve().relative_to(root.resolve())
        return True
    except (ValueError, OSError):
        return False


def describe_outputs(guide: dict, trial_dir: Path, final_cwd: Path | None) -> dict:
    files, directories, missing = [], [], []
    bases = [b for b in (final_cwd, trial_dir / "work") if b is not None]
    for name in output_paths(guide.get("outputs", [])):
        found = False
        for base in bases:
            path = base / name
            if path.is_symlink() or not inside(path, trial_dir) or not path.exists():
                continue
            found = True
            if path.is_dir():
                directories.append({"path": name, "resolved": str(path)})
            elif path.is_file():
                size = path.stat().st_size
                try:
                    digest = sha256_file(path) if size < HASH_LIMIT_BYTES else None
                except OSError:
                    digest = None
                files.append({"path": name, "resolved": str(path), "size_bytes": size, "sha256": digest})
            break
        if not found:
            missing.append(name)
    return {"files": files, "directories": directories, "named_but_not_found": missing}


def memory_bytes() -> int | None:
    try:
        for line in Path("/proc/meminfo").read_text().splitlines():
            if line.startswith("MemTotal:"):
                return int(line.split()[1]) * 1024
    except OSError:
        pass
    try:
        out = subprocess.run(["sysctl", "-n", "hw.memsize"], capture_output=True, text=True, check=True)
        return int(out.stdout.strip())
    except (OSError, ValueError, subprocess.CalledProcessError):
        return None


def os_name() -> str:
    try:
        for line in Path("/etc/os-release").read_text().splitlines():
            if line.startswith("PRETTY_NAME="):
                return line.split("=", 1)[1].strip('"')
    except OSError:
        pass
    return platform.platform()


def repository_commit() -> str | None:
    try:
        out = subprocess.run(["git", "-C", str(REPO), "rev-parse", "HEAD"], capture_output=True, text=True, check=True)
        return out.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return os.environ.get("GITHUB_SHA")


def read_small(path: Path) -> str | None:
    return path.read_text(errors="replace").strip() if path.is_file() and not path.is_symlink() else None


def runner_facts(trial_dir: Path, run: dict) -> dict:
    existing = trial_dir if trial_dir.exists() else Path("/")
    return {
        "os": os_name(),
        "platform": platform.platform(),
        "cpu_count": os.cpu_count(),
        "memory_bytes": memory_bytes(),
        "disk_free_bytes_at_start": int(run["disk_free_kb_at_start"]) * 1024 if run.get("disk_free_kb_at_start", "").isdigit() else None,
        "disk_free_bytes_at_end": shutil.disk_usage(existing).free,
        "session_python": read_small(trial_dir / "record" / "session-python.txt"),
        "session_conda": read_small(trial_dir / "record" / "session-conda.txt"),
        "receipt_python": platform.python_version(),
        "gpu_present": bool(shutil.which("nvidia-smi") or Path("/dev/nvidia0").exists()),
    }


PYTHON_SETUP = {"ok", "failed_used_default", "failed_used_runner_python"}


def python_facts(guide: dict, setup: str | None) -> dict | None:
    """Which Python the trial asked for, who chose it, and whether it could be set up."""
    if setup is None:
        return None
    if setup not in PYTHON_SETUP:
        raise SystemExit(f"Unknown Python setup outcome {setup!r}")
    named = guide_python(guide)
    return {"requested": named or DEFAULT_PYTHON, "chosen_by": "guide" if named else "harness_default",
            "setup": setup}


def build_receipt(trial_dir: Path, record: dict, python_setup: str | None = None) -> dict:
    guide = record["attributes"]["run_guide"]
    record_dir = trial_dir / "record"
    sha = guide_hash(guide)
    script_sha_file = record_dir / "guide.sha256"
    script_sha = script_sha_file.read_text().strip() if script_sha_file.is_file() else None
    if script_sha is not None and script_sha != sha:
        raise SystemExit(f"The script was generated from a different guide ({script_sha}) than the record holds ({sha})")

    run = {row[0]: row[1] if len(row) > 1 else "" for row in read_tsv(record_dir / "run.tsv")}
    finished = "finished_at" in run
    timed_out = run.get("timed_out") == "yes" or not finished
    session_exit = int(run["session_exit"]) if run.get("session_exit", "").lstrip("-").isdigit() else None

    begins, ends = {}, {}
    for row in read_tsv(record_dir / "status.tsv"):
        if row[0] == "begin" and len(row) >= 3:
            begins[int(row[1])] = to_seconds(row[2])
        elif row[0] == "end" and len(row) >= 5 and int(row[1]) not in ends:
            ends[int(row[1])] = (to_seconds(row[2]), int(row[3]), row[4])

    last_begun = max(begins) if begins else None
    steps = []
    for n, step in enumerate(guide["steps"], start=1):
        log_file = record_dir / "logs" / f"{n}.log"
        log_tail = log_file.read_text(encoding="utf-8", errors="replace") if log_file.is_file() and not log_file.is_symlink() else ""
        entry = {"number": n, "title": step["title"], "shell": step["shell"], "manual": is_manual(step["shell"]), "status": "not_run",
                 "exit_code": None, "seconds": None, "log_tail": log_tail}
        if n in begins:
            ended_by_timeout = timed_out and n == last_begun and (n not in ends or ends[n][2] == "exit")
            if ended_by_timeout:
                entry["status"] = "timed_out"
                entry["seconds"] = round(ends[n][0] - begins[n], 3) if n in ends else None
            elif n in ends:
                end, code, how = ends[n]
                entry["exit_code"] = code
                entry["seconds"] = round(end - begins[n], 3)
                if code != 0:
                    entry["status"] = "failed"
                elif how == "exit":
                    entry["status"] = "ended_session"
                else:
                    entry["status"] = "completed"
            else:
                entry["status"] = "failed"
                entry["exit_code"] = session_exit
        steps.append(entry)

    first_bad = next((s for s in steps if s["status"] != "completed"), None)
    if first_bad is None:
        result = "completed"
    elif first_bad["status"] == "timed_out":
        result = "timed_out"
    elif first_bad["status"] == "not_run":
        result = "not_started"
    else:
        result = f"failed_at_step_{first_bad['number']}"

    final_cwd_file = record_dir / "final-cwd"
    final_cwd = None
    if final_cwd_file.is_file():
        candidate = Path(final_cwd_file.read_text().strip())
        if inside(candidate, trial_dir):
            final_cwd = candidate

    receipt = {
        "receipt_version": RECEIPT_VERSION,
        "record_id": record["id"],
        "record_kind": record.get("kind"),
        "record_name": record.get("name"),
        "repository_commit": repository_commit(),
        "run_guide_sha256": sha,
        "run_guide_status": guide.get("status"),
        "runner": runner_facts(trial_dir, run),
        "python": python_facts(guide, python_setup),
        "started_at": run.get("started_at"),
        "finished_at": run.get("finished_at"),
        "timeout_seconds": int(run["timeout_seconds"]) if run.get("timeout_seconds", "").isdigit() else None,
        "session_exit": session_exit,
        "steps": steps,
        "result": result,
        "manual_steps": [s["number"] for s in steps if s["manual"]],
    }
    if result.startswith("failed_at_step_"):
        receipt["likely_cause"] = likely_cause(first_bad["log_tail"], first_bad["exit_code"])
        receipt["last_error_line"] = last_error_line(first_bad["log_tail"])
    receipt["outputs"] = describe_outputs(guide, trial_dir, final_cwd)
    return receipt


def write_receipt(trial_dir: Path, record: dict, out_dir: Path, python_setup: str | None = None) -> dict:
    receipt = build_receipt(trial_dir, record, python_setup)
    (out_dir / "logs").mkdir(parents=True, exist_ok=True)
    for step in receipt["steps"]:
        if step["log_tail"]:
            (out_dir / "logs" / f"{step['number']}.log").write_text(step["log_tail"], encoding="utf-8")
    (out_dir / "receipt.json").write_text(json.dumps(receipt, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return receipt


def markdown_cell(text: str) -> str:
    text = re.sub(r"\s+", " ", str(text)).strip()
    for char, escaped in (("&", "&amp;"), ("<", "&lt;"), (">", "&gt;"), ("|", "\\|"), ("`", "&#96;")):
        text = text.replace(char, escaped)
    return text


def summary(receipt: dict) -> str:
    lines = [f"### Run guide trial: {markdown_cell(receipt['record_id'])}", "",
             f"Result: **{markdown_cell(receipt['result'])}**"]
    if "likely_cause" in receipt:
        lines.append(f"Likely cause: {markdown_cell(receipt['likely_cause'])}")
    python = receipt.get("python")
    if python:
        lines.append(f"Python {markdown_cell(python['requested'])}, chosen by {python['chosen_by']}, setup {python['setup']}")
    if receipt.get("manual_steps"):
        lines.append("Steps with only comments, not exercised: " + ", ".join(map(str, receipt["manual_steps"])))
    lines += ["", "| Step | Title | Status | Exit code | Seconds |", "| --- | --- | --- | --- | --- |"]
    for step in receipt["steps"]:
        lines.append("| {} | {} | {} | {} | {} |".format(
            step["number"], markdown_cell(step["title"]), step["status"],
            "" if step["exit_code"] is None else step["exit_code"],
            "" if step["seconds"] is None else round(step["seconds"]),
        ))
    return "\n".join(lines) + "\n"


def receipts_table(folder: Path) -> str:
    """One row per receipt.json under a folder of downloaded receipts."""
    rows = ["| Record | Result | Failed step | Likely cause | Last error line |", "| --- | --- | --- | --- | --- |"]
    for path in sorted(folder.rglob("receipt.json")):
        receipt = json.loads(path.read_text(encoding="utf-8"))
        bad = next((s for s in receipt["steps"] if s["status"] != "completed"), None)
        failed = f"{bad['number']}. {bad['title']}" if bad and receipt["result"] != "completed" else ""
        error = receipt.get("last_error_line") or (last_error_line(bad["log_tail"]) if failed else "")
        rows.append("| {} | {} | {} | {} | {} |".format(
            markdown_cell(receipt["record_id"]), markdown_cell(receipt["result"]), markdown_cell(failed),
            markdown_cell(receipt.get("likely_cause", "")), markdown_cell(error[:200])))
    return "\n".join(rows) + "\n"


# Candidates

GPU_RE = re.compile(r"\bcuda\b|cuda:\d|\bgpus?\b|nvidia|\bA100\b|\bH100\b|flash[-_]attn", re.I)
INSTALL_RE = re.compile(r"\bpip3? install\b|\bconda (env )?create\b|\bconda install\b|\bmamba (create|install)\b|\buv (pip|sync|add)\b", re.I)
BLOCKED_RE = re.compile(r"\bsudo\b|\bdocker\b|\bsingularity\b|\bapptainer\b|\bpodman\b", re.I)
PLACEHOLDER_RE = re.compile(r"<[A-Za-z][A-Za-z0-9_ .-]*>|/path/to\b|\byour\b|\bYOUR[_-]", re.I)
SIZE_RE = re.compile(r"(\d+(?:\.\d+)?)\s*(GB|TB|GiB|TiB)\b")
MAX_STEPS = 4
# About 3 GB of fp32 weights.
MAX_PARAMETERS = 750_000_000
MAX_STATED_GB = 3.0


def load_checkpoints(specs_glob: str = SPECS_GLOB) -> dict[str, list[dict]]:
    by_record: dict[str, list[dict]] = {}
    for path in sorted(glob.glob(specs_glob)):
        try:
            spec = json.loads(Path(path).read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if not isinstance(spec, dict):
            continue
        for item in spec.get("structured") or []:
            if isinstance(item, dict) and item.get("checkpoint"):
                by_record.setdefault(spec.get("record_id", ""), []).append(item)
    return by_record


GPU_OPTIONAL_RE = re.compile(
    r"optional|not (required|needed)|no GPU is|recommended|\bon (a )?CPU\b|falls back to cpu|mode cpu|"
    r"GPU (need|requirement)s?\b[^.]*not stated", re.I)


def mentions_gpu(guide: dict) -> bool:
    text = "\n".join([*(s["shell"] for s in guide["steps"]), *guide.get("prerequisites", [])])
    return bool(GPU_RE.search(text))


def requires_gpu(guide: dict) -> bool:
    """A step mentions a GPU, or a prerequisite does without calling it optional."""
    if any(GPU_RE.search(s["shell"]) for s in guide["steps"]):
        return True
    return any(GPU_RE.search(p) and not GPU_OPTIONAL_RE.search(p) for p in guide.get("prerequisites", []))


def assess(record: dict, checkpoints: list[dict]) -> tuple[bool, list[str], int | None]:
    """Whether a guide looks cheap to try on a CPU runner, the reasons, and the parameter count used."""
    guide = record["attributes"]["run_guide"]
    shell = "\n".join(s["shell"] for s in guide["steps"])
    prose = "\n".join([*guide.get("prerequisites", []), *guide.get("limitations", [])])
    reasons: list[str] = []
    if requires_gpu(guide):
        return False, ["needs a GPU or CUDA"], None
    if len(guide["steps"]) > MAX_STEPS:
        return False, [f"{len(guide['steps'])} steps"], None
    if not INSTALL_RE.search(shell):
        return False, ["no pip or conda install"], None
    if BLOCKED_RE.search(shell):
        return False, ["needs sudo or a container runtime"], None
    if PLACEHOLDER_RE.search(shell):
        return False, ["has a placeholder or refers to the reader's own data"], None
    if any(is_manual(s["shell"]) for s in guide["steps"]):
        return False, ["has a manual step (comments only)"], None
    for number, unit in SIZE_RE.findall(shell + "\n" + prose):
        size = float(number) * (1024 if unit.startswith("T") else 1)
        if size > MAX_STATED_GB:
            return False, [f"names a size of {number} {unit}"], None

    lowered = shell.lower()
    named = [c for c in checkpoints
             if str(c["checkpoint"]).lower() in lowered
             or (c.get("weights_url") and "/".join(str(c["weights_url"]).rstrip("/").split("/")[-2:]).lower() in lowered)]
    relevant = named or checkpoints
    if named and any(c.get("gated") for c in named):
        return False, ["named checkpoint is gated"], None
    if not named and checkpoints and all(c.get("gated") for c in checkpoints):
        return False, ["every checkpoint in the family is gated"], None
    counts = [c["parameters"] for c in relevant if isinstance(c.get("parameters"), (int, float))]
    parameters = int(max(counts)) if counts else None
    if parameters is not None and parameters > MAX_PARAMETERS:
        return False, [f"{parameters / 1e6:.0f}M parameters"], parameters

    reasons.append("GPU mentioned but not as required" if mentions_gpu(guide) else "no GPU mentioned")
    reasons.append(f"{len(guide['steps'])} steps")
    reasons.append("installs with pip or conda")
    if parameters is None:
        reasons.append("parameter count unknown")
    elif named:
        reasons.append(f"{parameters / 1e6:.0f}M parameters in the named checkpoint")
    else:
        reasons.append(f"{parameters / 1e6:.0f}M parameters, largest in the family (no checkpoint named in the steps)")
    return True, reasons, parameters


def candidates(entities: Path = ENTITIES, specs_glob: str = SPECS_GLOB) -> list[dict]:
    checkpoints = load_checkpoints(specs_glob)
    found = []
    for record in records_with_guides(entities):
        ok, reasons, parameters = assess(record, checkpoints.get(record["id"], []))
        if ok:
            found.append({"id": record["id"], "name": record.get("name"), "kind": record.get("kind"),
                          "steps": len(record["attributes"]["run_guide"]["steps"]),
                          "parameters": parameters, "why": reasons})
    found.sort(key=lambda c: (c["steps"], c["parameters"] is None, c["parameters"] or 0, c["id"]))
    return found


# Workflow matrix


def matrix(ids_text: str, timeout_minutes: str, entities: Path = ENTITIES) -> dict:
    ids = ids_text.split()
    if not ids:
        raise SystemExit("No record ids given")
    if len(ids) > MAX_IDS:
        raise SystemExit(f"At most {MAX_IDS} record ids, got {len(ids)}")
    if len(set(ids)) != len(ids):
        raise SystemExit("A record id is repeated")
    for record_id in ids:
        if not ID_RE.match(record_id):
            raise SystemExit(f"Not a record id: {record_id!r}")
    try:
        minutes = int(float(timeout_minutes))
    except ValueError:
        raise SystemExit(f"timeout_minutes is not a number: {timeout_minutes!r}")
    if not 1 <= minutes <= MAX_TIMEOUT_MINUTES:
        raise SystemExit(f"timeout_minutes must be between 1 and {MAX_TIMEOUT_MINUTES}")
    include = []
    for record_id in ids:
        named = guide_python(find_record(record_id, entities)["attributes"]["run_guide"])
        include.append({"id": record_id, "python": named or DEFAULT_PYTHON,
                        "python_chosen_by": "guide" if named else "harness_default"})
    # The session stops itself at timeout_minutes; the step and job limits are backstops above it,
    # so that a receipt is still written when the session has to be killed.
    return {"matrix": {"include": include}, "default_python": DEFAULT_PYTHON,
            "timeout_minutes": minutes, "session_seconds": minutes * 60,
            "step_timeout_minutes": minutes + 5, "job_timeout_minutes": minutes + 30}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--entities", type=Path, default=ENTITIES, help=argparse.SUPPRESS)
    parser.add_argument("--specs-glob", default=SPECS_GLOB, help=argparse.SUPPRESS)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("script")
    p.add_argument("record_id")
    p.add_argument("--out", type=Path)
    p = sub.add_parser("receipt")
    p.add_argument("trial_dir", type=Path)
    p.add_argument("record_id")
    p.add_argument("--out-dir", type=Path)
    p.add_argument("--python-setup", choices=sorted(PYTHON_SETUP))
    p = sub.add_parser("candidates")
    p.add_argument("--limit", type=int, default=25)
    p.add_argument("--json", action="store_true")
    p = sub.add_parser("matrix")
    p.add_argument("--ids", required=True)
    p.add_argument("--timeout-minutes", required=True)
    p = sub.add_parser("summary")
    p.add_argument("receipt", type=Path)
    args = parser.parse_args(argv)

    if args.command == "script":
        text = render_script(find_record(args.record_id, args.entities))
        if args.out:
            args.out.write_text(text, encoding="utf-8")
        else:
            sys.stdout.write(text)
    elif args.command == "receipt":
        record = find_record(args.record_id, args.entities)
        recorded_id = args.trial_dir / "record" / "record-id"
        if recorded_id.is_file() and recorded_id.read_text().strip() != record["id"]:
            raise SystemExit(f"{args.trial_dir} holds a run of another record")
        receipt = write_receipt(args.trial_dir, record, args.out_dir or args.trial_dir / "receipt", args.python_setup)
        print(f"{receipt['record_id']}: {receipt['result']}")
        if receipt["result"] == "not_started":
            return 1
    elif args.command == "candidates":
        found = candidates(args.entities, args.specs_glob)[: args.limit]
        if args.json:
            print(json.dumps(found, indent=2))
        else:
            for c in found:
                print(f"{c['id']}\t{c['name']}\t{c['steps']} steps\t{'; '.join(c['why'])}")
    elif args.command == "matrix":
        plan = matrix(args.ids, args.timeout_minutes, args.entities)
        for key, value in plan.items():
            print(f"{key}={json.dumps(value, separators=(',', ':')) if key == 'matrix' else value}")
    elif args.command == "summary":
        if args.receipt.is_dir():
            sys.stdout.write(receipts_table(args.receipt))
        else:
            sys.stdout.write(summary(json.loads(args.receipt.read_text(encoding="utf-8"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
