"""Extract a small, pinned subset of an external ontology (MIREOT style).

For each seed term, keeps the term and all its named superclasses or superproperties, with
their type declarations, subclass and subproperty links, labels and definitions. Nothing
else is copied, so the subset cannot add axioms the vocabulary does not rely on.

Usage: python scripts/kg/extract_terms.py SOURCE OUTPUT --source-url URL --term IRI [--term IRI ...]
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

import rdflib
from rdflib import OWL, RDF, RDFS, URIRef
from rdflib.namespace import SKOS

DEFINITION = URIRef("http://purl.obolibrary.org/obo/IAO_0000115")
KEEP = [RDFS.label, RDFS.comment, SKOS.definition, DEFINITION]
TYPES = {OWL.Class, RDFS.Class, OWL.ObjectProperty, OWL.DatatypeProperty, OWL.AnnotationProperty, RDF.Property}
PARENTS = [RDFS.subClassOf, RDFS.subPropertyOf]


def english(literal: rdflib.term.Node) -> bool:
    return isinstance(literal, rdflib.Literal) and literal.language in (None, "en")


def extract(source: rdflib.Graph, seeds: list[URIRef]) -> rdflib.Graph:
    subset = rdflib.Graph()
    seen: set[URIRef] = set()
    todo = list(seeds)
    while todo:
        term = todo.pop()
        if term in seen:
            continue
        seen.add(term)
        for kind in source.objects(term, RDF.type):
            if kind in TYPES:
                subset.add((term, RDF.type, kind))
        for predicate in PARENTS:
            for parent in source.objects(term, predicate):
                if isinstance(parent, URIRef):
                    subset.add((term, predicate, parent))
                    todo.append(parent)
        for predicate in KEEP:
            for value in source.objects(term, predicate):
                if english(value):
                    subset.add((term, predicate, value))
    missing = [s for s in seeds if not any(subset.triples((s, None, None)))]
    if missing:
        raise SystemExit(f"Terms not found in source: {', '.join(map(str, missing))}")
    return subset


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("source")
    parser.add_argument("output")
    parser.add_argument("--source-url", required=True)
    parser.add_argument("--version", default="")
    parser.add_argument("--term", action="append", required=True)
    args = parser.parse_args()
    data = Path(args.source).read_bytes()
    source = rdflib.Graph().parse(data=data, format=rdflib.util.guess_format(args.source) or "xml")
    subset = extract(source, [URIRef(t) for t in args.term])
    lines = sorted(line for line in subset.serialize(format="nt").splitlines() if line.strip())
    header = [
        f"# Subset of {args.source_url} {args.version}".rstrip(),
        f"# Source sha256 {hashlib.sha256(data).hexdigest()}",
        "# Generated by scripts/kg/extract_terms.py; do not edit by hand.",
        "# Seeds: " + " ".join(sorted(args.term)),
    ]
    Path(args.output).write_text("\n".join(header + lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(lines)} triples to {args.output}")


if __name__ == "__main__":
    main()
