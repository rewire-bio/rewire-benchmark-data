"""List everything the current record store holds, so the new design can account for all of it.

Usage: python3 kb/inventory.py > kb/INVENTORY.md

For every record kind: how many records, every top-level field, every attribute with the number
of records that carry it and the type of value it holds, every link relation with the kinds it
points at, and every status. Nothing may be dropped by the migration without appearing here
first with a reason.
"""
import collections
import glob
import json


def records():
    for path in sorted(glob.glob("data/entities/*.jsonl")) + sorted(glob.glob("data/evidence/*/*.jsonl")):
        with open(path) as handle:
            for line in handle:
                if line.strip():
                    yield json.loads(line)


def kind_of(value):
    if isinstance(value, bool):
        return "true/false"
    if isinstance(value, (int, float)):
        return "number"
    if isinstance(value, str):
        return "text"
    if isinstance(value, list):
        return "list"
    if isinstance(value, dict):
        return "object"
    return "null"


def main():
    count = collections.Counter()
    attributes = collections.defaultdict(collections.Counter)
    types = collections.defaultdict(lambda: collections.defaultdict(collections.Counter))
    links = collections.defaultdict(collections.Counter)
    statuses = collections.defaultdict(collections.Counter)
    top = collections.defaultdict(collections.Counter)
    kind_by_id = {}
    pending = []
    for r in records():
        k = r["kind"]
        kind_by_id[r["id"]] = k
        count[k] += 1
        statuses[k][r.get("status")] += 1
        for field in r:
            top[k][field] += 1
        for name, value in (r.get("attributes") or {}).items():
            attributes[k][name] += 1
            types[k][name][kind_of(value)] += 1
        for link in r.get("links") or []:
            pending.append((k, link["relation"], link["target_id"]))
    for k, relation, target in pending:
        links[k][(relation, kind_by_id.get(target, "missing"))] += 1
    print("# Inventory of the current record store\n")
    print("Generated by `kb/inventory.py`. Every kind, attribute, link and status the store holds, with counts.\n")
    print("| Kind | Records | Attributes | Link relations |\n| --- | --- | --- | --- |")
    for k, n in count.most_common():
        print(f"| {k} | {n} | {len(attributes[k])} | {len({rel for rel, _ in links[k]})} |")
    print(f"\nTotal: {sum(count.values())} records.\n")
    for k, n in count.most_common():
        print(f"## {k} ({n})\n")
        print("Status: " + ", ".join(f"`{s}` {c}" for s, c in statuses[k].most_common()) + "\n")
        if links[k]:
            print("| Link | Points at | Count |\n| --- | --- | --- |")
            for (relation, target), c in sorted(links[k].items(), key=lambda kv: -kv[1]):
                print(f"| {relation} | {target} | {c} |")
            print()
        if attributes[k]:
            print("| Attribute | Records | Share | Value |\n| --- | --- | --- | --- |")
            for name, c in attributes[k].most_common():
                kinds = ", ".join(t for t, _ in types[k][name].most_common())
                print(f"| {name} | {c} | {round(100 * c / n)}% | {kinds} |")
            print()


if __name__ == "__main__":
    main()
