"""Build batch.jsonl and claims.csv for the Kedzierska et al. 2025 AvgBIO and average batch rows.

Usage: python3 -I extract_avg.py <additional-file-1.xlsx> <repository-root> <batch-folder>

Reads the pinned Additional file 1 workbook (archived in
data/omics/gfm-guides-20261014-kedzierska2025/artifacts/) with the stdlib OOXML reader, asserts its
SHA-256, the sheet titles, model headers, metric block labels and dataset labels, and transcribes the
single-value (whole-dataset) cells of the 'AvgBIO' and 'Average batch' blocks of sheets TableS6 and
TableS7. These are the 176 cells the first extraction (gfm-guides-20261014-kedzierska2025) skipped
for want of metric concepts. Every result links to an evaluation that is already in the store; the
script asserts that each one exists.

It also reports, without asserting, how far each printed AvgBIO and average batch value is from the
mean of the component cells in the same column, as a consistency check for the reviewer.
"""
import csv, glob, hashlib, json, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ooxml import read_sheets  # noqa: E402

XLSX_SHA = "7adee1211206c4071981a402617c293048baeeeaf415b68ecd13383678003b5e"
XLSX_URL = "https://static-content.springer.com/esm/art%3A10.1186%2Fs13059-025-03574-x/MediaObjects/13059_2025_3574_MOESM1_ESM.xlsx"
P = "gfm-guides-20261014-kedzierska2025"
SRC_XLSX = f"{P}-source-additional-file-1"
DATE = "2026-10-14"
REVIEWER_NOTE = ("Extraction agent for rewire-benchmark-data issue #163 (metric concepts for the genomic foundation model "
                 "guide evidence); extraction only, not a review. Pending an independent review-evidence pass.")

xlsx, repo, out = sys.argv[1], sys.argv[2], sys.argv[3]
assert hashlib.sha256(open(xlsx, "rb").read()).hexdigest() == XLSX_SHA, "workbook hash mismatch"
sheets = read_sheets(xlsx)

store_evals = set()
for path in glob.glob(os.path.join(repo, "data/evidence/evaluations/*.jsonl")):
    for line in open(path, encoding="utf-8"):
        store_evals.add(json.loads(line)["id"])
store_results = set()
for path in glob.glob(os.path.join(repo, "data/evidence/results/*.jsonl")):
    for line in open(path, encoding="utf-8"):
        rid = json.loads(line)["id"]
        if rid.startswith(P):
            store_results.add(rid)
assert len(store_results) == 602, len(store_results)


def cell(sheet, ref):
    v = sheets[sheet].get(ref)
    return None if v is None else v[0]


def general(raw):
    """Excel 'General' display of a stored number: shortest decimal, no trailing '.0'."""
    s = repr(float(raw))
    return s[:-2] if s.endswith(".0") else s


MODEL_COLS = [("HVG", "C", "hvg"), ("Harmony", "E", "harmony"), ("scVI", "G", "scvi"), ("scGPT random", "I", "scgpt-random"),
              ("scGPT kidney", "K", "scgpt-kidney"), ("scGPT blood", "M", "scgpt-blood"), ("scGPT human", "O", "scgpt-human"),
              ("Geneformer", "Q", "geneformer")]
BIO_ROWS = ["Pancreas (16k)", "Pancreas (8k)", "PBMC (12k)", "PBMC (95k)", "Immune (330k)", "Tabula Sapiens (483k)"]
BATCH_ROWS = ["Pancreas (16k)", "Pancreas (8k)", "PBMC (12k)", "Immune (330k)", "Tabula Sapiens (483k)"]
DSLUG = {"Pancreas (16k)": "pancreas-16k", "Pancreas (8k)": "pancreas-8k", "PBMC (12k)": "pbmc-12k", "PBMC (95k)": "pbmc-95k",
         "Immune (330k)": "immune-330k", "Tabula Sapiens (483k)": "tabula-sapiens-483k"}
# printed block label, first row, last row; the component blocks are only read for the consistency check
BLOCKS = {"ASW": (3, 8), "NMI": (9, 14), "ARI": (15, 20), "AvgBIO": (21, 26),
          "Batch integration": (27, 31), "PCR": (32, 36), "Average batch": (37, 41)}
TARGETS = [  # block, concept, slug, qualifier, components
    ("AvgBIO", "avg-bio", "avg-bio",
     "AvgBIO (mean of cell-type ASW, NMI and ARI; NMI and ARI on Louvain clusters at the best-NMI resolution)",
     ["ASW", "NMI", "ARI"]),
    ("Average batch", "average-batch-score", "average-batch",
     "average batch score (mean of batch integration score and PCR batch score)",
     ["Batch integration", "PCR"]),
]

records, claims_rows, checks = [], [], []
for sheet, pslug, title_start, space in [
        ("TableS6", "emb", "Table S6 Scores for cell embeddings generated by the models.", "full embedding dimensions"),
        ("TableS7", "umap", "Table S7 Scores for UMAP of the cell embeddings generated by the models.", "UMAP projection of the embedding")]:
    assert cell(sheet, "A1").startswith(title_start), (sheet, cell(sheet, "A1"))
    assert cell(sheet, "B2") == "Dataset"
    for label, col, _ in MODEL_COLS:
        assert cell(sheet, f"{col}2") == label, (sheet, col, cell(sheet, f"{col}2"))
    for block, (r0, r1) in BLOCKS.items():
        assert cell(sheet, f"A{r0}") == block, (sheet, r0, cell(sheet, f"A{r0}"))
        rows = BIO_ROWS if r1 - r0 == 5 else BATCH_ROWS
        for i, ds in enumerate(rows):
            assert cell(sheet, f"B{r0 + i}") == ds, (sheet, r0 + i, cell(sheet, f"B{r0 + i}"))
    for block, concept, slug, qual, comps in TARGETS:
        r0, r1 = BLOCKS[block]
        rows = BIO_ROWS if r1 - r0 == 5 else BATCH_ROWS
        for i, ds in enumerate(rows):
            r = r0 + i
            for label, col, cslug in MODEL_COLS:
                raw = cell(sheet, f"{col}{r}")
                rng = cell(sheet, f"{chr(ord(col) + 1)}{r}")
                assert re.fullmatch(r"-?\d+(\.\d+)?", raw), (sheet, col, r, raw)
                assert re.fullmatch(r"-?\d\.\d{3} \(-?\d\.\d{3} - -?\d\.\d{3}\)", rng), (sheet, col, r, rng)
                printed = general(raw)
                # consistency check against the component cells in the same column and dataset row
                parts = [float(cell(sheet, f"{col}{BLOCKS[c][0] + i}")) for c in comps]
                checks.append((sheet, f"{col}{r}", block, abs(float(raw) - sum(parts) / len(parts))))
                eid = f"{P}-eval-{pslug}-{DSLUG[ds]}-{cslug}"
                assert eid in store_evals, eid
                rid = f"{P}-result-{pslug}-{DSLUG[ds]}-{cslug}-{slug}"
                assert rid not in store_results, rid
                loc = (f"Additional file 1, sheet '{sheet}' cell {col}{r}, metric block '{block}', row '{ds}', column '{label}' "
                       f"(single-value column)")
                pname = "cell embedding" if pslug == "emb" else "UMAP-projected embedding"
                records.append({
                    "id": rid, "kind": "result",
                    "name": f"{label} {pname} on {ds} (Kedzierska et al. 2025): {slug}",
                    "description": "Reported measurement transcribed from the pinned source. Not independently reproduced.",
                    "status": "needs_review", "facets": {}, "source_ids": [SRC_XLSX],
                    "links": [{"relation": "evaluation", "target_id": eid}],
                    "attributes": {
                        "metric": concept, "metric_direction": "higher", "unit": "unitless",
                        "printed_value": printed, "numeric_value": printed,
                        "metric_qualifier": f"{qual}; whole dataset; {space}",
                        "source_locator": loc,
                        "review": {
                            "method": ["deterministic-table-parse"],
                            "method_note": (f"Read sheet '{sheet}' of the pinned workbook with a stdlib OOXML reader "
                                            "(extract/ooxml.py); sheet title, model headers C2:Q2, all seven metric labels in column A "
                                            "and dataset labels in column B asserted; printed_value is the Excel General display of the "
                                            "stored number."),
                            "reviewer": ["claude"], "reviewer_note": REVIEWER_NOTE, "date": DATE,
                            "artifact_sha256": XLSX_SHA, "retrieval_url": XLSX_URL,
                            "note": ("Extracted, not reviewed. Same column reading as the reviewed batch "
                                     "gfm-guides-20261014-kedzierska2025: the single-value column is the whole-dataset score. "
                                     "The review-evidence pass must re-check this value against the pinned artifact."),
                        },
                        "missing_metadata": {"uncertainty": {"reason": "unreported"}},
                        "raw_xml_value": raw, "workbook_number_format": "General",
                    }})
                claims_rows.append([rid, SRC_XLSX, loc, printed, "result"])

for r in records:  # the store keeps missing_metadata keys sorted (normalizeAttributes)
    if "missing_metadata" in r["attributes"]:
        r["attributes"]["missing_metadata"] = dict(sorted(r["attributes"]["missing_metadata"].items()))
records.sort(key=lambda r: r["id"])
ids = [r["id"] for r in records]
assert len(ids) == len(set(ids)) == 176, len(ids)
with open(os.path.join(out, "batch.jsonl"), "w", encoding="utf-8") as f:
    for r in records:
        f.write(json.dumps(r, ensure_ascii=False, separators=(",", ":")) + "\n")
claims_rows.sort()
with open(os.path.join(out, "claims.csv"), "w", encoding="utf-8", newline="") as f:
    w = csv.writer(f)
    w.writerow(["record_id", "source_id", "locator", "printed_value", "review_scope"])
    w.writerows(claims_rows)

for block in ("AvgBIO", "Average batch"):
    diffs = [c for c in checks if c[2] == block]
    worst = max(diffs, key=lambda c: c[3])
    over = [c for c in diffs if c[3] > 0.001]
    print(f"{block}: {len(diffs)} cells; largest |printed - mean of components| = {worst[3]:.6f} at {worst[0]} {worst[1]}; "
          f"{len(over)} cells differ by more than 0.001")
print(len(records), "results")
